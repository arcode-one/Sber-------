/* Демонстрационные ответы прототипа. Все цифры условные — заменятся ответами модели. */
(function () {
  // short — подписи для узкого экрана (на мобильном длинные слова не помещаются в колонку)
  function chart(title, bars, labels, short) {
    return '<div class="chart-stub" role="img" aria-label="' + title + ' — заглушка графика">' +
      '<div class="chart-stub__head"><span>' + title + '</span><span class="chart-stub__tag">График — заглушка</span></div>' +
      '<div class="chart-stub__bars">' + bars.map(function (h) { return '<span style="height:' + h + '%"></span>'; }).join('') + '</div>' +
      '<div class="chart-stub__axis">' + labels.map(function (l, i) { return short ? '<span><span class="chart-stub__full">' + l + '</span><span class="chart-stub__short" aria-hidden="true">' + short[i] + '</span></span>' : '<span>' + l + '</span>'; }).join('') + '</div>' +
      '</div>';
  }

  // Таблица: подписи колонок дублируются в data-label — на мобильном строки показываются карточками
  function table(head, rows, num) {
    return '<div class="table-wrap"><table class="table">' +
      '<thead><tr>' + head.map(function (h, i) { return '<th' + (num[i] ? ' class="num"' : '') + '>' + h + '</th>'; }).join('') + '</tr></thead>' +
      '<tbody>' + rows.map(function (r) {
        return '<tr>' + r.map(function (c, i) {
          return '<td' + (num[i] ? ' class="num"' : '') + (i ? ' data-label="' + head[i] + '"' : '') + '>' + c + '</td>';
        }).join('') + '</tr>';
      }).join('') + '</tbody></table></div>';
  }

  var DEMO = '<p class="note">Демонстрационный ответ: данные условные. В рабочей версии ответ формируется по внутренней документации со ссылками на источники.</p>';

  var answers = [
    {
      match: /тариф|профи/i,
      html:
        '<h4>Тарифы на продукт «Профи»</h4>' +
        '<p>Для продукта доступны <strong>три тарифа</strong>. Выбор зависит от размера аванса и срока договора — чем выше аванс, тем ниже удорожание.</p>' +
        table(['Тариф', 'Аванс', 'Срок', 'Удорожание в год'], [
          ['Старт', 'от 10%', '12–36 мес.', 'от 9,5%'],
          ['Оптимальный', 'от 20%', '12–48 мес.', 'от 7,9%'],
          ['Премиум', 'от 30%', '12–60 мес.', 'от 6,4%']
        ], [0, 1, 1, 1]) +
        chart('Доля сделок по тарифам, %', [38, 82, 54], ['Старт', 'Оптимальный', 'Премиум'], ['Старт', 'Оптим.', 'Премиум']) +
        '<p>Клиентам с сезонной выручкой предложите <mark>гибкий график платежей</mark> — он доступен на всех тарифах.</p>' +
        DEMO
    },
    {
      match: /возражен/i,
      html:
        '<h4>Работа с возражениями клиентов</h4>' +
        '<p>Используйте схему <strong>«Выслушать — уточнить — аргументировать — договориться»</strong>. Частые возражения и ответы:</p>' +
        '<ol>' +
        '<li><strong>«Дорого».</strong> Покажите экономию на налогах: лизинговые платежи относятся на расходы, НДС принимается к вычету.</li>' +
        '<li><strong>«Возьмём кредит».</strong> Сравните требования к залогу и скорость решения: по лизингу предмет сам является обеспечением.</li>' +
        '<li><strong>«Подумаем».</strong> Уточните, что мешает решению, и зафиксируйте следующий шаг с датой.</li>' +
        '</ol>' +
        DEMO
    },
    {
      match: /документ|сделк/i,
      html:
        '<h4>Документы для оформления сделки</h4>' +
        '<p>Базовый пакет для юридического лица:</p>' +
        '<ul>' +
        '<li>заявка на лизинг по форме компании;</li>' +
        '<li>учредительные документы и решение об одобрении сделки;</li>' +
        '<li>бухгалтерская отчётность за последний завершённый год и квартал;</li>' +
        '<li>паспорт руководителя и подписанта;</li>' +
        '<li>коммерческое предложение или спецификация поставщика.</li>' +
        '</ul>' +
        '<p>Для ИП вместо учредительных документов — <mark>выписка из ЕГРИП</mark> и налоговая декларация.</p>' +
        DEMO
    },
    {
      match: /срок|внедрен|этап/i,
      html:
        '<h4>Срок внедрения продукта</h4>' +
        '<p>В среднем <strong>от 3 до 10 рабочих дней</strong> от заявки до передачи предмета лизинга.</p>' +
        table(['Этап', 'Ответственный', 'Срок'], [
          ['Приём заявки и документов', 'КМ', '1 день'],
          ['Рассмотрение и решение', 'Риски', '1–3 дня'],
          ['Подписание договора', 'КМ, клиент', '1 день'],
          ['Поставка и передача', 'Поставщик', '1–5 дней']
        ], [0, 0, 1]) +
        chart('Средний срок по этапам, дни', [20, 60, 20, 100], ['Заявка', 'Решение', 'Договор', 'Поставка']) +
        DEMO
    }
  ];

  var fallback =
    '<h4>Что удалось найти</h4>' +
    '<p>По вашему запросу в документации есть несколько материалов. Коротко:</p>' +
    '<ul>' +
    '<li>основные условия описаны в продуктовой инструкции;</li>' +
    '<li>порядок действий — в регламенте продаж;</li>' +
    '<li>готовые формулировки для клиента — в шаблонах документов.</li>' +
    '</ul>' +
    '<p>Уточните продукт или этап сделки — подскажу точнее.</p>' +
    DEMO;

  window.KM_ANSWERS = {
    get: function (q) {
      for (var i = 0; i < answers.length; i++) if (answers[i].match.test(q)) return answers[i].html;
      return fallback;
    }
  };
})();
